import { useState } from 'react'
import { Download, FileSpreadsheet, FileText } from 'lucide-react'
import { downloadReport } from '../api/reports'
import { getApiError } from '../api/axios'
import { Button, Notice, PageHeader } from '../components/common'

export default function Reports() {
  const [busy, setBusy] = useState('')
  const [notice, setNotice] = useState('')
  async function download(key, path, name) {
    setBusy(key); setNotice('')
    try { await downloadReport(path, name); setNotice('Report download started.') }
    catch (e) { setNotice(getApiError(e)) }
    finally { setBusy('') }
  }
  return <>
    <PageHeader eyebrow="EXPORTS" title="Reports" description="Download reports generated by the backend. Report contents are not fabricated in the frontend." />
    {notice && <Notice type={notice.includes('started') ? 'success' : 'error'} onClose={() => setNotice('')}>{notice}</Notice>}
    <div className="reports-grid">
      <article className="panel report-card"><div className="report-icon report-csv"><FileSpreadsheet size={24} /></div><span className="eyebrow">INVENTORY EXPORT</span><h2>Device inventory</h2><p>CSV report of devices registered in NMVS, supplied by the backend.</p><div className="report-format">CSV <span>Comma-separated values</span></div><Button variant="secondary" onClick={() => download('csv', '/reports/devices/csv', 'devices_report.csv')} disabled={!!busy}>{busy === 'csv' ? 'Preparing…' : <><Download size={16} /> Download CSV</>}</Button></article>
      <article className="panel report-card"><div className="report-icon report-pdf"><FileText size={24} /></div><span className="eyebrow">EXECUTIVE OVERVIEW</span><h2>Network health summary</h2><p>Executive network health report generated from backend data.</p><div className="report-format">PDF <span>Portable document</span></div><Button onClick={() => download('pdf', '/reports/executive/pdf', 'executive_summary.pdf')} disabled={!!busy}>{busy === 'pdf' ? 'Preparing…' : <><Download size={16} /> Download PDF</>}</Button></article>
    </div>
  </>
}
